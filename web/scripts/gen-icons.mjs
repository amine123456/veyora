// Dev-only generator: builds the dashboard/home SVG icon sprite components from the
// Hugeicons Pro "Rounded / Stroke" set. Run it when the icon map below changes:
//
//   node scripts/gen-icons.mjs "D:/path/to/Rounded/Stroke"
//
// It reads each mapped Hugeicons file, recolors stroke/fill to currentColor, converts
// SVG attributes to JSX camelCase, and emits each as a reusable <symbol id="i-NAME">.
// The generated .tsx is committed; the Hugeicons folder is NOT needed to build or run.

