// Build filename -> absolute path index (first match wins) by walking the tree.
const index = new Map();
(function walk(dir) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full);
    else if (entry.endsWith('.svg') && !index.has(entry)) index.set(entry, full);
  }
})(ROOT);

const ATTR = {
  'stroke-width': 'strokeWidth',
  'stroke-linecap': 'strokeLinecap',
  'stroke-linejoin': 'strokeLinejoin',
  'stroke-miterlimit': 'strokeMiterlimit',
  'stroke-dasharray': 'strokeDasharray',
  'stroke-dashoffset': 'strokeDashoffset',
  'stroke-opacity': 'strokeOpacity',
  'fill-rule': 'fillRule',
  'clip-rule': 'clipRule',
  'fill-opacity': 'fillOpacity',
};

function symbolFor(id, file) {
  const path = index.get(file);
  if (!path) throw new Error(`Hugeicons file not found: ${file} (for i-${id})`);
  let svg = readFileSync(path, 'utf8');
  // Inner markup only.
  svg = svg.replace(/<svg[^>]*>/, '').replace(/<\/svg>/, '').trim();
  // Recolor the Hugeicons default ink to inherit from CSS.
  svg = svg.replace(/#141B34/gi, 'currentColor');
  // SVG attributes -> JSX camelCase.
  for (const [k, v] of Object.entries(ATTR)) svg = svg.replaceAll(`${k}=`, `${v}=`);
  // Indent the inner lines under the <symbol>.
  const inner = svg
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean)
    .map((l) => `          ${l}`)
    .join('\n');
  return `        <symbol id="i-${id}" viewBox="0 0 24 24" fill="none">\n${inner}\n        </symbol>`;
}

function render(map, includeLogo) {
  const symbols = Object.entries(map).map(([id, file]) => symbolFor(id, file));
  if (includeLogo) symbols.unshift(LOGO);
  return symbols.join('\n');
}

